import json
import logging
from typing import Dict, Any, List, Optional
import httpx

from app.core.config import settings
from app.models.finding import Finding
from app.schemas.remediation import RemediationGuidanceResponse

logger = logging.getLogger(__name__)


class AIRemediationService:
    """
    Isolated AI remediation service with deterministic rule-based fallback.
    Never invents unverified technical details or external CVEs.
    """

    @classmethod
    def generate_guidance(cls, finding: Finding) -> RemediationGuidanceResponse:
        # Check if an external AI provider is configured and an API key is present
        if settings.ai_configuration_ready:
            try:
                return cls._call_external_ai(finding)
            except Exception as e:
                logger.warning(
                    "External AI provider '%s' failed (%s); using rule-based fallback.",
                    settings.configured_ai_provider,
                    type(e).__name__,
                )
                fallback = cls._generate_rule_based_fallback(finding)
                fallback.uncertainty_or_missing_information = (
                    f"Note: Configured AI provider ({settings.configured_ai_provider}) was unreachable or returned an error ({type(e).__name__}). "
                    f"Engaged local rule-based remediation engine. {fallback.uncertainty_or_missing_information}"
                )
                return fallback

        # Default: Deterministic rule-based fallback
        return cls._generate_rule_based_fallback(finding)

    @classmethod
    def _generate_rule_based_fallback(cls, finding: Finding) -> RemediationGuidanceResponse:
        """
        Deterministic, transparent, rule-based remediation guidance.
        Clearly labeled as fallback, never pretending to be generated by an LLM.
        """
        pkg = finding.package_name or "the affected component"
        curr_ver = finding.installed_version or "unspecified version"
        fix_ver = finding.fixed_version
        cve = finding.cve_id or "unspecified CVE"
        sev = finding.severity

        # 1. Vulnerability explanation
        explanation = (
            f"Vulnerability '{finding.title}' identified in {pkg} ({curr_ver}). "
            f"Classification: {sev} severity with a prioritization score of {finding.risk_score}/100. "
            f"Details: {finding.description.strip()}"
        )

        # 2. Potential impact
        impact_by_severity = {
            "Critical": "High risk of immediate system compromise, remote code execution, unauthorized data exfiltration, or complete loss of service confidentiality/integrity.",
            "High": "Significant potential for privilege escalation, security control bypass, unauthorized data manipulation, or denial of service.",
            "Medium": "Moderate security impact under specific environmental configurations or pre-existing low-level access.",
            "Low": "Limited security impact; requires rare preconditions or non-standard configurations to exploit.",
            "Informational": "Informational finding or security best-practice recommendation with minimal direct exploitation risk.",
        }
        potential_impact = impact_by_severity.get(
            sev, "Security exposure impacting component integrity or availability."
        )
        if finding.file_path:
            potential_impact += f" Affected source path: {finding.file_path}."

        # 3. Recommended remediation steps
        steps: List[str] = []
        if fix_ver:
            steps.append(
                f"Update '{pkg}' from version {curr_ver} to fixed version {fix_ver} in your package manager manifest."
            )
            steps.append("Audit dependent packages for version locking or peer dependency conflicts.")
            steps.append("Run dependency lockfile regenerators (e.g., npm install, pip compile, or uv lock).")
        else:
            steps.append(
                f"Check official security advisories or repository release notes for '{pkg}' to confirm if an official patch has been released."
            )
            steps.append(
                "If no fixed version is released yet, consider implementing input validation, network isolation, or temporary feature flags."
            )
            steps.append(
                "Evaluate whether an alternative, actively maintained library can replace this dependency."
            )

        steps.append("Execute your unit and integration test suite to verify backwards compatibility.")
        steps.append("Create a dedicated remediation task and record verification evidence upon testing.")

        # 4. Compatibility considerations
        compatibility = (
            f"Upgrading '{pkg}' may introduce breaking API changes if stepping across major semver versions. "
            "Review changelogs and release notes for deprecation notices before deploying to production."
        )

        # 5. Verification steps
        verification_steps: List[str] = [
            f"Inspect the lockfile or build artifact to ensure '{pkg}' reflects the patched version.",
            "Execute the security scanner or dependency audit tool to verify the vulnerability is no longer flagged.",
            "Perform smoke tests on features that directly invoke the affected code paths.",
            "Record manual or automated test logs as Verification Evidence in PatchPilot.",
        ]

        # 6. Uncertainty or missing information
        missing_info: List[str] = []
        if not finding.cve_id:
            missing_info.append("No standard CVE identifier provided in the scan data.")
        if not finding.package_name:
            missing_info.append("Specific package/library name was not provided.")
        if not finding.fixed_version:
            missing_info.append("No automated fixed version was specified; manual advisory lookup is required.")
        if not finding.file_path:
            missing_info.append("Exact file location was not specified in the finding record.")

        uncertainty = (
            "Known facts: Provided scan data only. "
            + (f"Missing details: {'; '.join(missing_info)}." if missing_info else "All primary scan fields were populated.")
            + " No external runtime telemetry or exploit confirmation was performed."
        )

        return RemediationGuidanceResponse(
            finding_id=finding.id,
            title=finding.title,
            severity=finding.severity,
            risk_score=finding.risk_score,
            vulnerability_explanation=explanation,
            potential_impact=potential_impact,
            recommended_remediation_steps=steps,
            compatibility_considerations=compatibility,
            verification_steps=verification_steps,
            uncertainty_or_missing_information=uncertainty,
            is_fallback=True,
            provider="rule-based-fallback",
            model=None,
        )

    @classmethod
    def _call_external_ai(cls, finding: Finding) -> RemediationGuidanceResponse:
        """
        External LLM provider call (e.g. OpenAI-compatible API).
        Constructs prompt, requests structured JSON response, parses and returns.
        """
        provider = (settings.configured_ai_provider or "").lower()
        api_key = (settings.AI_API_KEY or "").strip()
        model = settings.AI_MODEL or "gpt-4o-mini"
        endpoint = settings.AI_API_URL or "https://api.openai.com/v1/chat/completions"

        prompt = (
            "You are a software security assistant providing remediation guidance to a developer.\n"
            "STRICT RULES:\n"
            "- Do NOT invent or hallucinate CVE numbers, package versions, or systems that are not provided.\n"
            "- Clearly separate known facts from recommendations.\n"
            "- Do NOT attempt or generate automated patches or system modifications.\n"
            "- Respond with valid JSON matching the exact schema specified.\n\n"
            f"Finding Data:\n"
            f"- Title: {finding.title}\n"
            f"- Severity: {finding.severity}\n"
            f"- Risk Score: {finding.risk_score}\n"
            f"- Description: {finding.description}\n"
            f"- CVE: {finding.cve_id or 'Not provided'}\n"
            f"- Package: {finding.package_name or 'Not provided'}\n"
            f"- Installed Version: {finding.installed_version or 'Not provided'}\n"
            f"- Fixed Version: {finding.fixed_version or 'Not provided'}\n"
            f"- File Path: {finding.file_path or 'Not provided'}\n\n"
            "JSON response must include keys: "
            "vulnerability_explanation (string), potential_impact (string), "
            "recommended_remediation_steps (list of strings), compatibility_considerations (string), "
            "verification_steps (list of strings), uncertainty_or_missing_information (string)."
        )

        headers = {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        }
        payload = {
            "model": model,
            "messages": [
                {"role": "system", "content": "You are a secure coding assistant that outputs strictly valid JSON."},
                {"role": "user", "content": prompt},
            ],
            "response_format": {"type": "json_object"},
            "temperature": 0.2,
        }

        data = cls._post_to_provider(endpoint, headers, payload)
        return cls._parse_provider_response(data, finding, provider, model)

    @classmethod
    def _post_to_provider(cls, endpoint: str, headers: dict, payload: dict) -> Dict[str, Any]:
        with httpx.Client(timeout=15.0) as client:
            response = client.post(endpoint, headers=headers, json=payload)
            response.raise_for_status()
            return response.json()

    @classmethod
    def _parse_provider_response(
        cls, data: Dict[str, Any], finding: Finding, provider: str, model: str
    ) -> RemediationGuidanceResponse:
        content = data["choices"][0]["message"]["content"]
        parsed = json.loads(content)

        return RemediationGuidanceResponse(
            finding_id=finding.id,
            title=finding.title,
            severity=finding.severity,
            risk_score=finding.risk_score,
            vulnerability_explanation=str(parsed.get("vulnerability_explanation", finding.description)),
            potential_impact=str(parsed.get("potential_impact", "")),
            recommended_remediation_steps=list(parsed.get("recommended_remediation_steps", [])),
            compatibility_considerations=str(parsed.get("compatibility_considerations", "")),
            verification_steps=list(parsed.get("verification_steps", [])),
            uncertainty_or_missing_information=str(parsed.get("uncertainty_or_missing_information", "")),
            is_fallback=False,
            provider=provider,
            model=model,
        )
