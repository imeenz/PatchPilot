from typing import List, Optional
from pydantic import BaseModel, Field


class RemediationGuidanceResponse(BaseModel):
    finding_id: int
    title: str
    severity: str
    risk_score: float
    vulnerability_explanation: str = Field(..., description="Understandable explanation of the vulnerability")
    potential_impact: str = Field(..., description="Potential consequences if exploited")
    recommended_remediation_steps: List[str] = Field(..., description="Actionable step-by-step instructions to remediate")
    compatibility_considerations: str = Field(..., description="Potential breaking changes or compatibility caveats")
    verification_steps: List[str] = Field(..., description="Instructions to manually or automatically verify the fix")
    uncertainty_or_missing_information: str = Field(
        ..., description="Explicit acknowledgement of unknown details or assumptions"
    )
    is_fallback: bool = Field(..., description="True if generated by local deterministic fallback, False if LLM")
    provider: str = Field(..., description="Identifier of the remediation provider (e.g. 'rule-based-fallback', 'openai')")
    model: Optional[str] = Field(None, description="Model identifier if LLM was used")
    disclaimer: str = Field(
        default="AI and rule-based guidance requires human review. PatchPilot does not automatically modify source code or systems.",
        description="Safety notice regarding remediation suggestions"
    )
