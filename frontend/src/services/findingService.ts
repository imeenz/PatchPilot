import { apiClient } from './api';
import { demoApi, demoMode } from './demo/demoStore';
import type {
  FindingDetailResponse,
  FindingImportResponse,
  FindingListParams,
  FindingListResponse,
  RemediationGuidanceResponse,
} from '@/types';

export interface Sourced<T> {
  data: T;
  /** True only when the explicit, opt-in demo dataset is active. */
  isDemo: boolean;
}

export const findingService = {
  /** GET /api/v1/findings */
  async listFindings(params: FindingListParams = {}): Promise<Sourced<FindingListResponse>> {
    if (demoMode.isActive()) return { data: demoApi.listFindings(params), isDemo: true };
    const data = await apiClient<FindingListResponse>('/findings', {
      params: {
        page: params.page,
        size: params.size,
        severity: params.severity,
        source: params.source,
        has_cve: params.has_cve,
        query: params.query,
      },
    });
    return { data, isDemo: false };
  },

  /** GET /api/v1/findings/{id} */
  async getFinding(id: number): Promise<Sourced<FindingDetailResponse>> {
    if (demoMode.isActive()) return { data: demoApi.getFinding(id), isDemo: true };
    const data = await apiClient<FindingDetailResponse>(`/findings/${id}`);
    return { data, isDemo: false };
  },

  /**
   * POST /api/v1/findings/{id}/remediation-guidance
   * Guidance is generated by the backend (AI provider or its rule-based fallback).
   * It is not available for demo records, which the backend does not know about.
   */
  async getRemediationGuidance(id: number): Promise<Sourced<RemediationGuidanceResponse>> {
    if (demoMode.isActive()) {
      throw new Error(
        'Remediation guidance is generated by the backend and is not available for demo records. Exit demo mode to use it on real findings.'
      );
    }
    const data = await apiClient<RemediationGuidanceResponse>(`/findings/${id}/remediation-guidance`, {
      method: 'POST',
    });
    return { data, isDemo: false };
  },

  /**
   * POST /api/v1/findings/import
   * Accepts `{ findings: [...] }`. Always sent to the real backend; blocked in demo mode
   * so sample and real data are never mixed.
   */
  async importFindings(findings: Record<string, unknown>[]): Promise<FindingImportResponse> {
    if (demoMode.isActive()) {
      throw new Error('Importing is disabled while the demo dataset is active. Exit demo mode to import real findings.');
    }
    return apiClient<FindingImportResponse>('/findings/import', {
      method: 'POST',
      body: JSON.stringify({ findings }),
    });
  },
};
