import { useState } from 'react';
import { AlertCircle, Bot, Check, ChevronDown, Copy, Cpu, RefreshCw, Settings2, User } from 'lucide-react';
import type { UIChatMessage } from '@/types';
import { Markdown } from '@/components/markdown/Markdown';
import { RemediationGuidanceCard } from '@/features/findings/RemediationGuidanceCard';
import { copyText } from '@/utils/clipboard';
import { ImportResultCard } from './ImportResultCard';

interface Props {
  message: UIChatMessage;
  onRetry?: () => void;
  onAskAboutImport?: (text: string) => void;
  onAnalyzeFinding?: (findingId: number) => void;
}

function formatTime(iso: string) {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '';
  const sameDay = d.toDateString() === new Date().toDateString();
  return sameDay
    ? d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
    : d.toLocaleString([], { month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' });
}

/** Shows exactly what the backend reported about who produced the answer. */
export function ProviderBadge({ isFallback, provider, model }: { isFallback?: boolean; provider?: string | null; model?: string | null }) {
  if (isFallback) {
    return (
      <span
        className="inline-flex items-center gap-1 px-1.5 py-0.5 rounded border border-medium/35 bg-medium/10 text-medium text-[10px] font-mono"
        title={`Generated by the backend's deterministic rule-based fallback${provider ? ` (${provider})` : ''}, not by an AI model.`}
      >
        <Settings2 className="w-3 h-3" />
        Rule-based fallback
      </span>
    );
  }
  if (!provider) return null;
  return (
    <span
      className="inline-flex items-center gap-1 px-1.5 py-0.5 rounded border border-primary/30 bg-primary/10 text-accent text-[10px] font-mono"
      title="Generated by the AI provider configured on the backend."
    >
      <Cpu className="w-3 h-3" />
      AI · {provider}
      {model ? ` · ${model}` : ''}
    </span>
  );
}

export function MessageItem({ message, onRetry, onAskAboutImport, onAnalyzeFinding }: Props) {
  const [copied, setCopied] = useState(false);
  const [showGuidance, setShowGuidance] = useState(false);
  const isUser = message.role === 'user';

  if (message.localCard) {
    return (
      <div className="flex gap-3">
        <div className="w-8 h-8 rounded-lg bg-surface-2 border border-line text-fg-subtle flex items-center justify-center shrink-0">
          <Bot className="w-4 h-4" />
        </div>
        <div className="flex-1 min-w-0 space-y-1.5">
          <p className="text-[11px] text-fg-subtle">Shown in this view only. It is not saved to the conversation.</p>
          {message.localCard.kind === 'import-result' ? (
            <ImportResultCard
              result={message.localCard.result}
              fileName={message.localCard.fileName}
              format={message.localCard.format}
              onAsk={onAskAboutImport}
              onAnalyzeFinding={onAnalyzeFinding}
            />
          ) : (
            <RemediationGuidanceCard guidance={message.localCard.guidance} isLoading={false} error={null} onGenerate={() => {}} />
          )}
        </div>
      </div>
    );
  }

  const handleCopy = async () => {
    if (await copyText(message.content)) {
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    }
  };

  return (
    <div className={`group flex gap-3 ${isUser ? 'flex-row-reverse' : ''}`}>
      <div
        className={`w-8 h-8 rounded-lg flex items-center justify-center shrink-0 ${
          isUser ? 'bg-primary text-on-primary' : 'bg-surface-2 border border-line text-accent'
        }`}
        aria-hidden="true"
      >
        {isUser ? <User className="w-4 h-4" /> : <Bot className="w-4 h-4" />}
      </div>

      <div className={`flex flex-col min-w-0 max-w-[88%] sm:max-w-[80%] ${isUser ? 'items-end' : 'items-start'}`}>
        <div className={`flex flex-wrap items-center gap-2 mb-1 px-0.5 ${isUser ? 'flex-row-reverse' : ''}`}>
          <span className="text-xs font-semibold text-fg">{isUser ? 'You' : 'PatchPilot'}</span>
          {message.status === 'delivered' && (
            <time dateTime={message.createdAt} className="text-[11px] text-fg-subtle font-mono">
              {formatTime(message.createdAt)}
            </time>
          )}
          {!isUser && <ProviderBadge isFallback={message.isFallback} provider={message.provider} model={message.model} />}
        </div>

        <div
          className={`rounded-2xl px-4 py-3 ${
            isUser
              ? `bg-primary text-on-primary rounded-tr-sm ${message.status === 'pending' ? 'opacity-70' : ''} ${message.status === 'failed' ? 'ring-2 ring-critical/60' : ''}`
              : 'bg-surface border border-line rounded-tl-sm shadow-card'
          }`}
        >
          {isUser ? (
            <p className="whitespace-pre-wrap break-words text-sm leading-relaxed">{message.content}</p>
          ) : (
            <Markdown content={message.content} />
          )}
        </div>

        {isUser && message.status === 'pending' && (
          <span className="mt-1 text-[11px] text-fg-subtle">Sending…</span>
        )}
        {isUser && message.status === 'failed' && (
          <span className="mt-1 inline-flex items-center gap-2 text-[11px] text-critical">
            <AlertCircle className="w-3.5 h-3.5" />
            Not sent. The backend did not accept this message.
            {onRetry && (
              <button onClick={onRetry} className="inline-flex items-center gap-1 font-medium underline underline-offset-2 cursor-pointer">
                <RefreshCw className="w-3 h-3" /> Retry
              </button>
            )}
          </span>
        )}

        {!isUser && (
          <div className="mt-1 flex items-center gap-1 opacity-70 group-hover:opacity-100 focus-within:opacity-100 transition-opacity">
            <button
              type="button"
              onClick={handleCopy}
              className="inline-flex items-center gap-1 px-1.5 py-1 rounded text-[11px] text-fg-subtle hover:text-fg hover:bg-surface-2 cursor-pointer"
              aria-label="Copy response"
            >
              {copied ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}
              {copied ? 'Copied' : 'Copy'}
            </button>
            {message.structuredGuidance && (
              <button
                type="button"
                onClick={() => setShowGuidance((s) => !s)}
                aria-expanded={showGuidance}
                className="inline-flex items-center gap-1 px-1.5 py-1 rounded text-[11px] text-fg-subtle hover:text-fg hover:bg-surface-2 cursor-pointer"
              >
                <ChevronDown className={`w-3.5 h-3.5 transition-transform ${showGuidance ? 'rotate-180' : ''}`} />
                Structured guidance
              </button>
            )}
          </div>
        )}

        {showGuidance && message.structuredGuidance && (
          <div className="mt-2 w-full">
            <RemediationGuidanceCard guidance={message.structuredGuidance} isLoading={false} error={null} onGenerate={() => {}} />
          </div>
        )}
      </div>
    </div>
  );
}
